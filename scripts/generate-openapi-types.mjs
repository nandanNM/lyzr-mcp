import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

// Live OpenAPI specs for the two Lyzr hosts our hand-written clients
// (src/lyzr/*.ts) wrap. These specs can drift over time — this script
// generates a reference snapshot contributors can diff against when they
// suspect drift, per .claude/skills/lyzr-api-endpoint/SKILL.md.
const SPECS = [
  {
    name: "Lyzr Agent API",
    url: "https://agent-dev.test.studio.lyzr.ai/openapi.json",
    outputPath: new URL(
      "../src/lyzr/generated/agent-api-types.ts",
      import.meta.url,
    ),
  },
  {
    name: "Lyzr RAG API",
    url: "https://rag-dev.test.studio.lyzr.ai/openapi.json",
    outputPath: new URL(
      "../src/lyzr/generated/rag-api-types.ts",
      import.meta.url,
    ),
  },
];

async function generate({ name, url, outputPath }) {
  console.log(`Fetching ${name} spec from ${url} ...`);
  const ast = await openapiTS(url);

  const output = `/**
 * This file was auto-generated by openapi-typescript from the live
 * ${name} OpenAPI spec (${url}).
 *
 * Do not make direct changes to the file. It is NOT the source of truth for
 * the hand-written clients in src/lyzr/*.ts — it exists purely as a
 * reference/drift-detection aid. Run \`npm run generate:openapi-types\` to
 * regenerate, then diff against the relevant client's hand-written
 * interfaces when you suspect the live API has changed.
 */

${astToString(ast)}`;

  mkdirSync(dirname(outputPath.pathname), { recursive: true });
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath.pathname}`);
}

for (const spec of SPECS) {
  await generate(spec);
}
